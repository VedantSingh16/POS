export function translateText(text: string, locale: Locale): string {
  if (locale === "en") return text;
  const normalized = text.replace(/\s+/g, " ").trim();
  let translated: string | undefined = arabicMessages[normalized];
  if (!translated) translated = translateTemplate(normalized);
  if (!translated) return text;
  const leadingSpace = /^\s/.test(text) ? " " : "";
  const trailingSpace = /\s$/.test(text) ? " " : "";
  return `${leadingSpace}${translated}${trailingSpace}`;
}

function translateTemplate(text: string): string | undefined {
  for (const [source, target] of Object.entries(arabicTemplates)) {
    const placeholders = [...source.matchAll(/\{([a-zA-Z]+)\}/g)];
    const pattern = source
      .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
      .replace(/\\\{[a-zA-Z]+\\\}/g, "(.+?)");
    const match = new RegExp(`^${pattern}$`).exec(text);
    if (!match) continue;
    let translated = target;
    placeholders.forEach((placeholder, index) => {
      translated = translated.replace(placeholder[0], match[index + 1] ?? "");
    });
    return translated;
  }
  return undefined;
}
